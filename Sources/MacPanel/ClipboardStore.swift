import AppKit
import Combine
import Foundation
import ImageIO

struct ClipEntry: Codable, Identifiable, Equatable {
    enum Kind: String, Codable { case text, image, files }
    var id: UUID
    var created: Date
    var kind: Kind
    var preview: String
    var textFile: String?
    var imageFile: String?
    var thumbnailFile: String?
    var rtfFile: String?
    var fileURLs: [String]?
}

/// A maximum of 15 *copy operations*, persisted atomically on the local disk.
/// Images are loaded from disk only when their row is displayed or restored.
final class ClipboardStore: ObservableObject {
    @Published private(set) var entries: [ClipEntry] = []
    @Published var paused: Bool {
        didSet { UserDefaults.standard.set(paused, forKey: "clipboard.paused") }
    }
    private let pasteboard = NSPasteboard.general
    private var observedChangeCount: Int
    private let folder: URL
    private let indexFile: URL
    private let maximum = 15

    init() {
        paused = UserDefaults.standard.bool(forKey: "clipboard.paused")
        observedChangeCount = pasteboard.changeCount
        let base = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
        folder = base.appendingPathComponent("MacPanel/Clipboard", isDirectory: true)
        indexFile = folder.appendingPathComponent("history.json")
        try? FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
        if let data = try? Data(contentsOf: indexFile),
           let restored = try? JSONDecoder().decode([ClipEntry].self, from: data) {
            entries = Array(restored.prefix(maximum))
            for old in restored.dropFirst(maximum) { deleteAssets(old) }
        }
    }

    func captureIfChanged() {
        let count = pasteboard.changeCount
        guard count != observedChangeCount else { return }
        observedChangeCount = count
        guard !paused else { return }
        let types = pasteboard.types ?? []
        // Respect the conventional pasteboard privacy markers from password managers.
        let privateTypes: Set<String> = [
            "org.nspasteboard.ConcealedType",
            "org.nspasteboard.TransientType",
            "org.nspasteboard.AutoGeneratedType"
        ]
        guard !types.contains(where: { privateTypes.contains($0.rawValue) }) else { return }

        let identifier = UUID()
        var entry: ClipEntry?
        let now = Date()
        if let imageData = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff),
           let bitmap = NSBitmapImageRep(data: imageData),
           let png = bitmap.representation(using: .png, properties: [:]) {
            let filename = identifier.uuidString + ".png"
            do {
                try png.write(to: folder.appendingPathComponent(filename), options: .atomic)
                let thumbnailName = identifier.uuidString + "-preview.png"
                if let thumbnail = Self.makeThumbnail(png) {
                    try? thumbnail.write(to: folder.appendingPathComponent(thumbnailName), options: .atomic)
                }
                let thumbSaved = FileManager.default.fileExists(atPath: folder.appendingPathComponent(thumbnailName).path)
                entry = ClipEntry(id: identifier, created: now, kind: .image,
                                  preview: "Изображение \(bitmap.pixelsWide) × \(bitmap.pixelsHigh)",
                                  textFile: nil, imageFile: filename,
                                  thumbnailFile: thumbSaved ? thumbnailName : nil,
                                  rtfFile: nil, fileURLs: nil)
            } catch { return }
        } else if let urls = pasteboard.readObjects(forClasses: [NSURL.self],
                    options: [.urlReadingFileURLsOnly: true])?.compactMap({ ($0 as? NSURL)?.absoluteURL }),
                    !urls.isEmpty {
            entry = ClipEntry(id: identifier, created: now, kind: .files,
                              preview: urls.count == 1 ? urls[0].lastPathComponent : "Файлы: \(urls.count)",
                              textFile: nil, imageFile: nil, thumbnailFile: nil, rtfFile: nil,
                              fileURLs: urls.map(\.absoluteString))
        } else if let string = pasteboard.string(forType: .string), !string.isEmpty {
            var richName: String? = nil
            if let rtf = pasteboard.data(forType: .rtf) {
                let name = identifier.uuidString + ".rtf"
                if (try? rtf.write(to: folder.appendingPathComponent(name), options: .atomic)) != nil {
                    richName = name
                }
            }
            let textName = identifier.uuidString + ".txt"
            do {
                try string.write(to: folder.appendingPathComponent(textName), atomically: true, encoding: .utf8)
            } catch { return }
            entry = ClipEntry(id: identifier, created: now, kind: .text,
                              preview: String(string.prefix(120)).replacingOccurrences(of: "\n", with: " "),
                              textFile: textName, imageFile: nil, thumbnailFile: nil,
                              rtfFile: richName, fileURLs: nil)
        }
        guard let clip = entry else { return }
        entries.insert(clip, at: 0)
        trimAndPersist()
    }

    func restore(_ clip: ClipEntry) {
        pasteboard.clearContents()
        switch clip.kind {
        case .text:
            if let textName = clip.textFile,
               let value = try? String(contentsOf: folder.appendingPathComponent(textName), encoding: .utf8) {
                pasteboard.setString(value, forType: .string)
            }
            if let rtfName = clip.rtfFile,
               let bytes = try? Data(contentsOf: folder.appendingPathComponent(rtfName)) {
                pasteboard.setData(bytes, forType: .rtf)
            }
        case .files:
            let urls = (clip.fileURLs ?? []).compactMap(URL.init(string:))
            pasteboard.writeObjects(urls.map { $0 as NSURL })
        case .image:
            if let imageName = clip.imageFile,
               let data = try? Data(contentsOf: folder.appendingPathComponent(imageName)) {
                pasteboard.setData(data, forType: .png)
            }
        }
        // Restoring a record does not generate a new clipboard-history entry.
        observedChangeCount = pasteboard.changeCount
    }

    func image(for clip: ClipEntry) -> NSImage? {
        guard let filename = clip.thumbnailFile ?? clip.imageFile else { return nil }
        return NSImage(contentsOf: folder.appendingPathComponent(filename))
    }

    func remove(_ clip: ClipEntry) {
        entries.removeAll { $0.id == clip.id }
        deleteAssets(clip)
        persist()
    }

    func clear() {
        entries.forEach(deleteAssets)
        entries.removeAll()
        persist()
    }

    private func trimAndPersist() {
        while entries.count > maximum { deleteAssets(entries.removeLast()) }
        persist()
    }

    private func deleteAssets(_ clip: ClipEntry) {
        for filename in [clip.imageFile, clip.thumbnailFile, clip.rtfFile, clip.textFile].compactMap({ $0 }) {
            try? FileManager.default.removeItem(at: folder.appendingPathComponent(filename))
        }
    }

    private static func makeThumbnail(_ bytes: Data) -> Data? {
        guard let source = CGImageSourceCreateWithData(bytes as CFData, nil),
              let cgImage = CGImageSourceCreateThumbnailAtIndex(source, 0, [
                kCGImageSourceCreateThumbnailFromImageAlways: true,
                kCGImageSourceCreateThumbnailWithTransform: true,
                kCGImageSourceThumbnailMaxPixelSize: 160
              ] as CFDictionary) else { return nil }
        return NSBitmapImageRep(cgImage: cgImage).representation(using: .png, properties: [:])
    }

    private func persist() {
        guard let bytes = try? JSONEncoder().encode(entries) else { return }
        try? bytes.write(to: indexFile, options: .atomic)
    }
}
